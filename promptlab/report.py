"""Run reports: a readable Markdown summary, or plain JSON for scripts."""

import json
from datetime import datetime, timezone

from . import __version__


def build_entries(results, tests):
    """Pair test inputs with runner results into report-ready dicts."""
    entries = []
    for test, result in zip(tests, results):
        entries.append(
            {
                "name": test["name"],
                "input": test["input"],
                "status": "ok" if result["ok"] else "error",
                "output": result.get("content"),
                "error": result.get("error"),
                "latency_seconds": round(result.get("latency", 0.0), 3),
            }
        )
    return entries


def aggregate(entries):
    oks = [e for e in entries if e["status"] == "ok"]
    latencies = [e["latency_seconds"] for e in oks]
    return {
        "total": len(entries),
        "ok": len(oks),
        "error": len(entries) - len(oks),
        "latency_average_seconds": round(sum(latencies) / len(latencies), 3) if latencies else None,
    }


def build_markdown(meta, entries):
    totals = aggregate(entries)
    lines = [
        "# Prompt Lab Run Report",
        "",
        f"- Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- Prompt: {meta['prompt']} (version {meta['prompt_version']})",
        f"- Endpoint: {meta['base_url']} (model: `{meta['model']}`)",
        f"- Tests: {totals['ok']} ok, {totals['error']} failed"
        f" (average latency {totals['latency_average_seconds']}s)"
        if totals["latency_average_seconds"] is not None
        else f"- Tests: {totals['ok']} ok, {totals['error']} failed",
        "",
    ]
    for i, entry in enumerate(entries, start=1):
        lines.append(f"## Test {i}: {entry['name']} — {entry['status']}")
        lines.append("")
        lines.append("**Input:**")
        lines.append("")
        lines.append("```")
        lines.append(entry["input"])
        lines.append("```")
        lines.append("")
        if entry["status"] == "ok":
            lines.append("**Output:**")
            lines.append("")
            lines.append("```")
            lines.append(str(entry["output"]))
            lines.append("```")
            lines.append(f"*Latency: {entry['latency_seconds']}s*")
        else:
            lines.append("**Error:**")
            lines.append("")
            lines.append("```")
            lines.append(str(entry["error"]))
            lines.append("```")
        lines.append("")
    meta_block = "\n".join(lines)
    footer = (
        f"\n---\n*Generated by Prompt Lab v{__version__} — a local-first tool "
        "by Asdale Dynamics, LLC.*\n"
    )
    return meta_block + footer


def build_json(meta, entries):
    return json.dumps(
        {
            "tool": "promptlab",
            "promptlab_version": __version__,
            "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "prompt": meta["prompt"],
            "prompt_version": meta["prompt_version"],
            "base_url": meta["base_url"],
            "model": meta["model"],
            "summary": aggregate(entries),
            "tests": entries,
        },
        indent=2,
        ensure_ascii=False,
    )
